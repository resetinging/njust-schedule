const assert = require('assert')
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(ROOT, file), 'utf8')

const mainWxml = read('pages/main/main.wxml')
const mainWxss = read('pages/main/main.wxss')
const scheduleWxml = read('components/schedule-view/index.wxml')
const scheduleWxss = read('components/schedule-view/index.wxss')
const scheduleJs = read('components/schedule-view/index.js')
const profileWxml = read('components/settings-view/index.wxml')
const profileWxss = read('components/settings-view/index.wxss')
const profileJs = read('components/settings-view/index.js')

assert(mainWxml.includes("{{current === 1 ? 'is-active' : ''}}"))
assert(mainWxml.includes("{{current === 2 ? 'is-active' : ''}}"))
assert(mainWxss.includes('@keyframes tabPageIn'))
assert(scheduleWxml.includes("{{entering ? 'is-entering' : ''}}"))
assert(profileWxml.includes("{{entering ? 'is-entering' : ''}}"))
assert(scheduleWxss.includes('@keyframes scheduleChromeIn'))
assert(scheduleWxss.includes('@keyframes scheduleItemIn'))
assert(profileWxss.includes('@keyframes profileItemIn'))
assert(scheduleJs.includes('_playEntrance()'))
assert(profileJs.includes('_playEntrance(done)'))
assert(scheduleJs.includes('if (this._entranceTimer) clearTimeout(this._entranceTimer)'))
assert(profileJs.includes('if (this._entranceTimer) clearTimeout(this._entranceTimer)'))
assert(scheduleWxss.includes('prefers-reduced-motion: reduce'))
assert(profileWxss.includes('prefers-reduced-motion: reduce'))
assert(mainWxss.includes('prefers-reduced-motion: reduce'))

console.log('Page animation regression test passed [OK]')
