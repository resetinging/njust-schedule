UNKNOWN_CODE_PREFIXES = ("74", "99", "347", "359", "366", "367", "368", "373", "384")

# 非实体条目: 教务"借用"库里存在但并非教室, 过滤
NON_PHYSICAL = {"线上", "其它教室"}


def label_for(prefix: str):
    """前缀 → 显示楼名; 未收录返回 None(调用方回退原始前缀)"""
    return BUILDING_LABELS.get(str(prefix or "").strip())


def split_prefix(name: str):
    """教室名 → (前缀, 余下部分)。

    '345-101' → ('345', '-101'); '江阴致源B331' → ('江阴致源B', '331');
    '384栋405' → ('384栋405', '') (数字开头且无 '-' 的编号保持原样)
    """
    s = str(name or "")
    dash = s.find("-")
    if dash > 0:
        return s[:dash], s[dash:]
    m = re.match(r"^(\D+?)(?=\d)", s)
    if m:
        return m.group(1), s[len(m.group(1)):]
    return s, ""


def format_room_name(raw: str) -> str:
    """教室名归一化(借用页展示用):

    1. 去掉教务的 "(容量/已借)" 后缀 —— '345-101(40/0)' → '345-101'
    2. 前缀命中映射表时替换为楼名 —— '345-101' → '东区平房-101';
       '江阴致源B331' → '致源楼B331'
    3. 未收录前缀(347/99/384栋405/线上/其它教室 等)返回 "" —— 调用方过滤
    """
    name = re.sub(r"\(.*?\)", "", str(raw or "")).strip()
    name = re.sub(r"\s+", " ", name)
    if not name:
        return ""
    prefix, rest = split_prefix(name)
    if prefix in NON_PHYSICAL:
        return ""
    label = label_for(prefix)
    if label and rest and label != prefix:
        return label + rest
    if label:
        # 整名即房间/场馆名(如 "体育中心健美操房")——保持原样, 避免多个场馆
        # 被替换成同一个楼名而丢失区分度
        return name
    return ""
